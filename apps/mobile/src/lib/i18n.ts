export type MobileDictionary = DictionaryShape<typeof ar>;

const dictionaries: Record<MobileLocale, MobileDictionary> = {
  ar,
  en,
};

export function getMobileDictionary(locale: MobileLocale): MobileDictionary {
  return dictionaries[locale];
}

export function formatMobileCopy(template: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce((current, [key, value]) => current.replaceAll(`{${key}}`, String(value)), template);
}
